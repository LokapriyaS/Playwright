//For loop used for iterating over a range of values or a collection of items
//It allows you to execute a block of code multiple times based on a specified condition.
function forLoopExample() {
for (let i = 1; i <=5; i++) {
    console.log("Iteration:",i);
    }       
}
forLoopExample();

//Decrementing for loop
function decrementingForLoopExample(){
    for(let i=10;i>=5;i--){
        console.log("Decrementing Iteration:",i);

    }
}
decrementingForLoopExample();